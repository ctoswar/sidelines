// Flat ESLint config (ESLint 9), wired up the way create-next-app 15 does it:
// the Next.js shareable configs are eslintrc-format, so they go through
// FlatCompat. Rules are whatever `next/core-web-vitals` + `next/typescript`
// recommend — no repo-specific rule tuning on top, deliberately.
//
// `npm run lint` runs `eslint .` directly rather than `next lint`, which is
// deprecated as of Next 15.5 (and removed in 16).

import { dirname } from "path";
import { fileURLToPath } from "url";
import { FlatCompat } from "@eslint/eslintrc";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

const compat = new FlatCompat({
  baseDirectory: __dirname,
});

const eslintConfig = [
  {
    // next-env.d.ts is regenerated by `next dev`/`next build` and its
    // triple-slash reference is exactly what Next writes there — linting it
    // would flag (and --fix would break) generated code.
    ignores: [".next/**", ".next-standalone/**", "node_modules/**", "drizzle/**", "var/**", "next-env.d.ts"],
  },
  ...compat.extends("next/core-web-vitals", "next/typescript"),
  {
    // The repo's convention for deliberately unused bindings (ignored fetch
    // results, placeholder catch params) is a leading underscore.
    rules: {
      "@typescript-eslint/no-unused-vars": [
        "warn",
        {
          argsIgnorePattern: "^_",
          varsIgnorePattern: "^_",
          caughtErrorsIgnorePattern: "^_",
          ignoreRestSiblings: true,
        },
      ],
    },
  },
];

export default eslintConfig;
